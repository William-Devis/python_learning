"""
    return关键字的其他用法
    return 后边返回多个值
    使用多个变量分别接收各个返回值 这个操作 也属于解包
"""

def func():
    return 1 , 2 , 3 , [4,5,6]

r1 = func() # 只写一个变量接收 所有的返回值将会自动被打包成一个元组
print(r1)

a1 , a2 , a3 , a4 = func() # 书写对与返回值相应数量的变量接收 分开处理 这种也属于解包操作
print(a1 ,a2, a3, a4)

b1 , b2 = func() # 这里报错 不允许指定不同数量的变量接收
print(b1, b2)

print("-------------------------------------------------")

def func_1(a,b,c):
    print(a,b,c)

list1 = [1,2,3]
