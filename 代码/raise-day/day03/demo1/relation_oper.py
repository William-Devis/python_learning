"""
    关系(比较)运算符 最终的结果都是布尔类型
    ==
    !=
    >
    <
    >=
    <=
"""
a = 1
b = 2
print("a大于b:",a > b)
print("a小于b:",a < b)
print("a等等于b:",a == b)
print("a不等于b:",a != b)
print("a大于等于b:",a >= b)
print("a小于等于b:",a <= b)

# Python中的字符串 也可以直接使用关系运算符比较

print("a" > "A")
print("abc" > "abcd")
print("中" > "你")